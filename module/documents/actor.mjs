import { prototypeTokenDefaults } from "../helpers/token-settings.mjs";

/**
 * The system's Actor: a fallback portrait and the token defaults on creation, and the data model's roll data.
 * (Data preparation is in the data models: data/actor/base-actor.mjs and its subclasses.)
 * @extends {Actor}
 */
export class LordOfTheMysteriesActor extends Actor {
  /**
   * Fallback portrait used whenever an actor is created without a valid image.
   * Covers every creation path (UI, macros, compendium imports, module code),
   * not just the "Create Actor" dialog.
   * @type {Record<string, string>}
   */
  static DEFAULT_IMAGES = {
    character: "icons/svg/mystery-man.svg",
    npc: "icons/svg/mystery-man.svg"
  };

  /** @override */
  async _preCreate(data, options, user) {
    const allowed = await super._preCreate(data, options, user);
    if (allowed === false) return false;

    const validExtension = /\.(png|jpeg|webp|svg|gif|avif|bmp)$/i;
    if (!data.img || !validExtension.test(data.img)) {
      const fallback = LordOfTheMysteriesActor.DEFAULT_IMAGES[data.type] ?? "icons/svg/mystery-man.svg";
      this.updateSource({ img: fallback });
    }

    // Token defaults (helpers/token-settings.mjs): Health in bar 1, the world's name / bar display settings,
    // and player characters linked to their tokens.
    this.updateSource({ prototypeToken: prototypeTokenDefaults(data.type) });
  }

  /**
   * 
   * @override
   * Augment the actor's default getRollData() method by appending the data object
   * generated by the its DataModel's getRollData(), or null. This polymorphic 
   * approach is useful when you have actors & items that share a parent Document, 
   * but have slightly different data preparation needs.
   */
  getRollData() {
    return { ...super.getRollData(), ...this.system.getRollData?.() ?? null };
  }

  /**
   * Convert the actor document to a plain object.
   * 
   * The built in `toObject()` method will ignore derived data when using Data Models.
   * This additional method will instead use the spread operator to return a simplified
   * version of the data.
   * 
   * @returns {object} Plain object either via deepClone or the spread operator.
   */
  toPlainObject() {
    const result = {...this};

    // Simplify system data.
    result.system = this.system.toPlainObject();

    // Add items.
    result.items = this.items?.size > 0 ? this.items.contents : [];

    // Add effects.
    result.effects = this.effects?.size > 0 ? this.effects.contents : [];

    return result;
  }

}
